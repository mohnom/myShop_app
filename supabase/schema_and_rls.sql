-- 1. جدول التجار (merchont)
CREATE TABLE IF NOT EXISTS public.merchont (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL,
  maerchont_id_fkey UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  UNIQUE (maerchont_id_fkey)
);

-- 2. جدول العملاء (cutomers)
CREATE TABLE IF NOT EXISTS public.cutomers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL,
  customers_id_fkey UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  UNIQUE (customers_id_fkey)
);

-- 3. جدول الربط بين التاجر والعميل (connects)
CREATE TABLE IF NOT EXISTS public.connects (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "Name_merchont" TEXT NOT NULL,
  "Name_customer" TEXT NOT NULL,
  "ID_customer" BIGINT NOT NULL REFERENCES public.cutomers(id) ON DELETE CASCADE,
  "ID_merchont" BIGINT NOT NULL REFERENCES public.merchont(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  UNIQUE ("ID_customer", "ID_merchont")
);

-- 4. جدول المشتريات والديون (Content)
CREATE TABLE IF NOT EXISTS public."Content" (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "NameProduct" TEXT NOT NULL,
  price NUMERIC(12, 2) NOT NULL CHECK (price > 0),
  "Quantity" INTEGER NOT NULL DEFAULT 1 CHECK ("Quantity" > 0),
  "ID_Conect" BIGINT NOT NULL REFERENCES public.connects(id) ON DELETE CASCADE,
  "Date" TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  note TEXT
);

-- 5. جدول الدفعات المسددة (payments)
CREATE TABLE IF NOT EXISTS public.payments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "ID_Conect" BIGINT NOT NULL REFERENCES public.connects(id) ON DELETE CASCADE,
  amount NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
  date TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  note TEXT
);

-- 6. جدول أجهزة الإشعارات (user_devices)
CREATE TABLE IF NOT EXISTS public.user_devices (
  user_id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  fcm_token TEXT NOT NULL,
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- فهارس لتحسين سرعة الاستعلامات
CREATE INDEX IF NOT EXISTS idx_connects_merchant ON public.connects("ID_merchont");
CREATE INDEX IF NOT EXISTS idx_connects_customer ON public.connects("ID_customer");
CREATE INDEX IF NOT EXISTS idx_content_connect ON public."Content"("ID_Conect");
CREATE INDEX IF NOT EXISTS idx_payments_connect ON public.payments("ID_Conect");

-- تفعيل سياسات أمن الصفوف (Row-Level Security)
ALTER TABLE public.merchont ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.cutomers ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.connects ENABLE ROW LEVEL SECURITY;
ALTER TABLE public."Content" ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.payments ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_devices ENABLE ROW LEVEL SECURITY;

-- سياسة إدارة الأجهزة (المستخدم يدير رمزه فقط، والتاجر يقرأ الرمز لإرسال الإشعار)
DROP POLICY IF EXISTS "Users manage own device token" ON public.user_devices;
CREATE POLICY "Users manage own device token"
  ON public.user_devices FOR ALL
  TO authenticated
  USING (auth.uid() = user_id)
  WITH CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS "Authenticated read device tokens" ON public.user_devices;
CREATE POLICY "Authenticated read device tokens"
  ON public.user_devices FOR SELECT
  TO authenticated
  USING (true);
